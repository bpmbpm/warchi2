/* ============================================================
 * config.js — wArchi2-JS · Конфигурация пользовательского интерфейса
 * ------------------------------------------------------------
 * Файл подключается как обычный <script src="config.js"> до
 * основного скрипта. Это позволяет работать в локальном
 * режиме (file://) без CORS-ошибок (см. п. 2.1 задания).
 *
 * Изменения параметров вступают в силу при следующей загрузке
 * страницы (никаких сборщиков, бандлеров и серверов не нужно).
 * ============================================================ */
(function () {
  'use strict';

  /* ----------------------------------------------------------
   * 1. Тема оформления
   * ----------------------------------------------------------
   * 'light' — по умолчанию. Идентична оригинальному https://warchi.ru/
   *           (белый фон, фиолетовый акцент #6366f1).
   * 'dark'  — тёмная схема (включалась по умолчанию в ver1 до
   *           появления конфига).
   * Тема применяется к <html data-theme="..."> ещё до построения DOM,
   * чтобы избежать «вспышки» неправильной темы.
   * ---------------------------------------------------------- */
  const theme = 'light';

  /* ----------------------------------------------------------
   * 2. Язык интерфейса
   * ----------------------------------------------------------
   * Поддерживается переключение между ru / en / fr (см. п. 2.2).
   * Текущий язык сохраняется в localStorage.warchi_lang при
   * пользовательском выборе и переопределяет это значение.
   * ---------------------------------------------------------- */
  const language = 'ru';

  /* ----------------------------------------------------------
   * 3. Имя пользователя
   * ----------------------------------------------------------
   * По условию задачи окно авторизации исключено, все действия
   * выполняются под фиксированным пользователем (см. п. 1).
   * ---------------------------------------------------------- */
  const userName = 'user1';

  /* ----------------------------------------------------------
   * 4. Право доступа текущего пользователя
   * ----------------------------------------------------------
   * Допустимые значения и краткое описание (см. п. 2.1):
   *
   *   OWNER — Владелец модели. Полные права: чтение, запись,
   *           удаление, передача владельца, управление правами
   *           участников. На каждую модель — ровно один OWNER.
   *
   *   ADMIN — Администратор репозитория. Видит и редактирует
   *           все модели, типы и нотации; управляет правами
   *           пользователей. Не имеет права передавать чужое
   *           владение, но может назначать новых владельцев.
   *
   *   EDIT  — Редактор. Чтение всего и запись внутри назначенных
   *           ему моделей: добавление/перемещение/удаление узлов
   *           и связей, создание диаграмм. Не может удалить саму
   *           модель и не может менять права других пользователей.
   *
   *   VIEW  — Наблюдатель. Только чтение: открыть модель,
   *           посмотреть диаграммы, экспортировать в SVG/PNG.
   *           Любые операции записи отключены и подсвечены
   *           серым в интерфейсе.
   * ---------------------------------------------------------- */
  const role = 'OWNER';

  /* ----------------------------------------------------------
   * 5. Описание ролей (используется в UI для подсказок)
   * ---------------------------------------------------------- */
  const roleDescriptions = {
    OWNER: 'Владелец — полные права на модель и её удаление',
    ADMIN: 'Администратор — управление пользователями и всеми моделями',
    EDIT:  'Редактор — изменение содержимого назначенных моделей',
    VIEW:  'Наблюдатель — только просмотр и экспорт',
  };

  /* ----------------------------------------------------------
   * 6. UI-параметры
   * ---------------------------------------------------------- */
  const ui = {
    /* Показ приветственной плашки на главной (п. 2.3 требует false). */
    showWelcomeBanner: false,
    /* Высота нижней панели лога в пикселях, по умолчанию. */
    logPanelHeight: 140,
    /* Размер сетки на холсте в пикселях. */
    gridSize: 20,
    /* Привязка узлов к сетке по умолчанию. */
    snapToGrid: true,
    /* Показывать сетку на холсте. */
    showGrid: true,
    /* Отображать панель «Быстрые действия» на главной странице. */
    showQuickActions: true,
    /* Отображать панель «Последние действия» на главной странице. */
    showRecentActions: true,
  };

  /* ----------------------------------------------------------
   * 7. Список главного меню (см. п. 2.2)
   * ----------------------------------------------------------
   * Перечень пунктов и их соответствие view-id внутри SPA.
   * Если убрать пункт из массива — он исчезнет из шапки.
   * ---------------------------------------------------------- */
  const mainMenu = [
    { id: 'home',    label: 'Главная' },
    { id: 'models',  label: 'Модели' },
    { id: 'notations', label: 'Нотации' },
    { id: 'types',   label: 'Типы' },
    { id: 'shapes',  label: 'Формы' },
    { id: 'docs',    label: 'Документация' },
    { id: 'wiki',    label: 'Вики' },
  ];

  /* ----------------------------------------------------------
   * 8. Заголовок и версия приложения
   * ---------------------------------------------------------- */
  const appName = 'wArchi2-JS';
  const appVersion = 'v1.1.0';

  /* ----------------------------------------------------------
   * 9. Применение темы максимально рано.
   * ---------------------------------------------------------- */
  try {
    const savedTheme = localStorage.getItem('warchi_theme');
    document.documentElement.setAttribute('data-theme', savedTheme || theme);
  } catch (_) {
    document.documentElement.setAttribute('data-theme', theme);
  }

  /* ----------------------------------------------------------
   * 10. Экспорт во глобальное пространство — единая точка для
   *     основного скрипта (он подключается ниже).
   * ---------------------------------------------------------- */
  window.WARCHI_CONFIG = {
    theme,
    language,
    userName,
    role,
    roleDescriptions,
    ui,
    mainMenu,
    appName,
    appVersion,
  };
})();
